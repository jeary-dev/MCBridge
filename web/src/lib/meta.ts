import type { Metadata } from "next";

const OG_IMAGE = {
  url: "/og.png",
  width: 1200,
  height: 630,
  alt: "MCBridge: your Minecraft server, live in Discord",
};

/** Title, description, canonical URL and Open Graph / Twitter tags for one page. */
export function pageMeta({
  title,
  description,
  path,
  absoluteTitle = false,
}: {
  title: string;
  description: string;
  path: string;
  absoluteTitle?: boolean;
}): Metadata {
  const fullTitle = absoluteTitle ? title : `${title} · MCBridge`;
  return {
    title: absoluteTitle ? { absolute: title } : title,
    description,
    alternates: { canonical: path },
    openGraph: {
      type: "website",
      siteName: "MCBridge",
      url: path,
      title: fullTitle,
      description,
      images: [OG_IMAGE],
    },
    twitter: {
      card: "summary_large_image",
      title: fullTitle,
      description,
      images: [OG_IMAGE.url],
    },
  };
}
